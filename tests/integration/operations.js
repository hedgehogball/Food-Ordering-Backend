'use strict';
// This executable test uses only the dedicated loopback MySQL test port.
const assert = require('node:assert/strict');
const mysql = require('mysql2/promise');
const { initialize, createDatabase } = require('../../src/database');
const { createService } = require('../../src/dining/service');
const { createTakeaway } = require('../../src/takeaway');
const { createOperations, defaultSettings } = require('../../src/operations');
const domain = require('../../src/dining/domain');
const { dishes } = require('../../src/dining/menu');
(async () => {
  const admin = await mysql.createConnection({ host: '127.0.0.1', port: 33308, user: 'root' });
  const name = 'lj_operations_test_' + Date.now();
  await admin.query(`CREATE DATABASE ${name}`); await admin.end();
  const options = { host: '127.0.0.1', port: 33308, user: 'root', database: name, connectionLimit: 10 };
  let pool = mysql.createPool(options);
  try {
    await Promise.all([initialize(pool), initialize(pool)]);
    const roleOf = actor => ['owner', 'cashier'].includes(actor) ? actor : 'customer';
    let operations = createOperations(pool, { roleOf });
    const concurrentSettings = await Promise.allSettled([1, 2].map(() => operations.handle({ action: 'saveSettings', expectedVersion: 1, settings: defaultSettings() }, 'owner')));
    assert.equal(concurrentSettings.filter(result => result.status === 'fulfilled').length, 1);
    assert.equal(concurrentSettings.find(result => result.status === 'rejected').reason.code, 'SETTINGS_CHANGED');
    await assert.rejects(operations.handle({ action: 'saveSettings', expectedVersion: 2, settings: defaultSettings() }, 'cashier'), { code: 'FORBIDDEN' });
    await assert.rejects(operations.handle({ action: 'dashboard' }, 'customer'), { code: 'FORBIDDEN' });
    let dining = createService(createDatabase(pool), ['cashier'], { beforeNewSubmit: operations.beforeNewSubmit });
    let takeaway = createTakeaway(pool, ['cashier'], { beforeNewSubmit: operations.beforeNewSubmit });
    const session = await dining({ action: 'join', table: '09' }, 'guest');
    const items = [{ dishId: 'lamb-skewer', option: '微辣', quantity: 10 }];
    const order = { action: 'submit', table: '09', sessionId: session.id, requestId: 'operation:dining', note: '少盐', items, expectedTotal: 1300 };
    const bill = await dining(order, 'guest');
    const pickupInput = { action: 'submit', requestId: 'operation:pickup', name: '测试', phone: '13800000000', pickupAt: Date.now() + 3600000, note: '', items, expectedTotal: 1300 };
    const simultaneousPickup = await Promise.all(Array.from({ length: 10 }, () => takeaway(pickupInput, 'a'.repeat(64))));
    assert.equal(new Set(simultaneousPickup.map(result => result.order.id)).size, 1);
    const pickup = simultaneousPickup[0].order;
    await assert.rejects(takeaway({ ...pickupInput, requestId: 'operation:too-soon', pickupAt: Date.now() + 60000 }, 'a'.repeat(64)), { code: 'PICKUP_INVALID' });
    await Promise.all(Array.from({ length: 8 }, () => operations.handle({ action: 'dashboard' }, 'cashier')));
    const [[queueCount]] = await pool.query('SELECT COUNT(*) AS count FROM lj_print_jobs');
    assert.equal(Number(queueCount.count), 2);
    const dashboard = await operations.handle({ action: 'dashboard' }, 'cashier');
    assert.equal(dashboard.role, 'cashier'); assert.equal(dashboard.newOrderIds.length, 2);
    assert.equal(dashboard.printJobs.some(job => job.lines !== undefined), false);
    const kitchen = { action: 'advance', kind: 'dinein', sessionId: session.id, orderId: bill.orders[0].id, expectedStage: 'new', nextStage: 'cooking' };
    await Promise.all([operations.handle(kitchen, 'cashier'), operations.handle(kitchen, 'cashier')]);
    const cooking = await dining({ action: 'get', table: '09', sessionId: session.id }, 'guest');
    assert.equal(cooking.revision, bill.revision + 1);
    assert.equal(cooking.orders[0].fulfillment, 'cooking'); assert.equal(cooking.status, 'open');
    await operations.handle({ ...kitchen, expectedStage: 'cooking', nextStage: 'ready' }, 'cashier');
    await assert.rejects(operations.handle(kitchen, 'cashier'), { code: 'STATE_CHANGED' });
    await operations.handle({ action: 'advance', kind: 'takeaway', orderId: pickup.id, expectedStage: 'new', nextStage: 'cooking' }, 'cashier');
    const printRequest = { action: 'requestPrint', kind: 'dinein', sessionId: session.id, orderId: bill.orders[0].id };
    const initialJob = (await operations.handle(printRequest, 'cashier')).job;
    assert.equal((await operations.handle(printRequest, 'cashier')).job.id, initialJob.id);
    const reprint = { ...printRequest, reprint: true, requestId: 'reprint:request-1' };
    const reprinted = await Promise.all([operations.handle(reprint, 'cashier'), operations.handle(reprint, 'cashier')]);
    assert.equal(reprinted[0].job.id, reprinted[1].job.id); assert.notEqual(reprinted[0].job.id, initialJob.id);
    await assert.rejects(operations.handle({ ...reprint, requestId: '' }, 'cashier'), { code: 'TOKEN_INVALID' });
    assert.deepEqual((await operations.handle({ action: 'getTicket', jobId: initialJob.id }, 'cashier')).job.lines, initialJob.lines);
    const firstAck = (await operations.handle({ action: 'markPrinted', jobId: initialJob.id }, 'cashier')).job;
    assert.equal(firstAck.status, 'printed');
    assert.equal((await operations.handle({ action: 'markPrinted', jobId: initialJob.id }, 'cashier')).job.printedAt, firstAck.printedAt);
    const date = new Date(Date.now() + 8 * 3600000).toISOString().slice(0, 10);
    const statsInput = { action: 'stats', dateFrom: date, dateTo: date };
    const unpaid = await operations.handle(statsInput, 'cashier');
    assert.equal(unpaid.submittedOrders, 2); assert.equal(unpaid.submittedTotal, 2600); assert.equal(unpaid.paidTotal, 0);
    const readyBill = await dining({ action: 'get', table: '09', sessionId: session.id }, 'guest');
    const checkout = await dining({ action: 'checkout', table: '09', sessionId: session.id, revision: readyBill.revision }, 'guest');
    await dining({ action: 'confirmPaid', table: '09', sessionId: session.id, revision: checkout.revision, expectedTotal: 1300 }, 'cashier');
    await takeaway({ action: 'complete', id: pickup.id, expectedTotal: 1300 }, 'cashier');
    const paid = await operations.handle(statsInput, 'cashier');
    assert.equal(paid.paidOrders, 2); assert.equal(paid.paidTotal, 2600);
    assert.equal(paid.dineinPaidTotal, 1300); assert.equal(paid.takeawayPaidTotal, 1300); assert.equal(paid.pendingOrders, 0);
    assert.equal(paid.topDishes[0].quantity, 20); assert.equal(paid.receipts.length, 2); assert.equal(paid.truncated, false);
    assert.equal((await operations.handle({ action: 'stats', dateFrom: '2020-01-01', dateTo: '2020-01-01' }, 'cashier')).paidTotal, 0);
    const guests = Array.from({ length: 20 }, (_, index) => 'capacity-guest-' + index);
    const joined = await Promise.all(guests.map(actor => dining({ action: 'join', table: '19' }, actor)));
    await Promise.all(guests.map((actor, index) => dining({ ...order, table: '19', sessionId: joined[0].id, requestId: 'capacity:order-' + index }, actor)));
    assert.equal((await dining({ action: 'get', table: '19', sessionId: joined[0].id }, guests[0])).total, 26000);
    const settings = (await operations.handle({ action: 'publicSettings' }, 'customer')).settings;
    await operations.handle({ action: 'saveSettings', expectedVersion: settings.version, settings: { ...settings, open: false } }, 'owner');
    assert.equal((await operations.handle({ action: 'publicSettings' }, 'customer')).acceptingNow, false);
    assert.equal((await dining(order, 'guest')).orders.length, 1);
    assert.equal((await takeaway(pickupInput, 'a'.repeat(64))).order.id, pickup.id);
    await assert.rejects(takeaway({ ...pickupInput, requestId: 'operation:closed' }, 'a'.repeat(64)), { code: 'SHOP_CLOSED' });
    const other = await dining({ action: 'join', table: '10' }, 'guest');
    await assert.rejects(dining({ ...order, table: '10', sessionId: other.id, requestId: 'operation:closed' }, 'guest'), { code: 'SHOP_CLOSED' });
    // Valid large bills exercise response sizing rather than only tiny example orders.
    const broadItems = dishes.filter(dish => !dish.soldOut).flatMap(dish => dish.options.map(option => ({ dishId: dish.id, option, quantity: Math.ceil((dish.minQuantity || 1) / dish.options.length) })));
    const broadTotal = broadItems.reduce((sum, item) => sum + dishes.find(dish => dish.id === item.dishId).price * item.quantity, 0);
    for (let number = 20; number <= 36; number++) {
      const table = String(number), time = Date.now();
      const busy = domain.newSession(table, require('node:crypto').randomUUID(), time);
      domain.join(busy, 'load-guest');
      for (let index = 0; index < 20; index++) domain.submit(busy, 'load-guest', { requestId: 'load:' + number + ':' + index, items: broadItems, note: '厨房忙时容量验证', expectedTotal: broadTotal }, time);
      await pool.execute('INSERT INTO lj_dining_sessions (id,document) VALUES (?,?)', [busy.id, JSON.stringify(busy)]);
      await pool.execute('UPDATE lj_dining_tables SET document=? WHERE id=?', [JSON.stringify({ id: table, sessionId: busy.id }), table]);
    }
    const largeDashboard = await operations.handle({ action: 'dashboard' }, 'cashier');
    assert.equal(largeDashboard.truncated, true);
    assert.ok(Buffer.byteLength(JSON.stringify(largeDashboard), 'utf8') < 601000, 'cloud dashboard must stay bounded for valid large bills');
    assert.equal(largeDashboard.printJobs.some(job => job.lines), false);
    await pool.end(); pool = mysql.createPool(options); await initialize(pool);
    operations = createOperations(pool, { roleOf });
    assert.equal((await operations.handle({ action: 'getTicket', jobId: initialJob.id }, 'cashier')).job.status, 'printed');
    assert.equal((await operations.handle({ action: 'publicSettings' }, 'customer')).settings.open, false);
    console.log('PASS MySQL operations: concurrent settings/migrations, authorization, preparation and closing guards, retry recovery, kitchen stages, durable unique tickets/reprints, paid-only reports, restart persistence, bounded large-bill dashboard');
  } finally { await pool.end(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
